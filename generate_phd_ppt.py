def table_slide(title, headers, rows, n=None):
    slide = prs.slides.add_slide(BLANK_LAYOUT)
    add_bg_shapes(slide, "content")
    _title_bar(slide, title)
    nr = len(rows) + 1
    nc = len(headers)
    table = slide.shapes.add_table(nr, nc, Inches(0.8), Inches(1.3),
                                   Inches(11.7), Inches(0.45) * nr).table
    for c, h in enumerate(headers):
        cell = table.cell(0, c)
        cell.text = h
        for p in cell.text_frame.paragraphs:
            p.font.size = Pt(13)
            p.font.bold = True
            p.font.color.rgb = WHITE
            p.font.name = FONT_ACCENT
        tc = cell._tc; tcPr = tc.get_or_add_tcPr()
        sf = tcPr.makeelement(qn('a:solidFill'), {})
        sf.append(sf.makeelement(qn('a:srgbClr'), {'val': '1B1F3B'}))
        tcPr.append(sf)
    for r, rd in enumerate(rows):
        for c, v in enumerate(rd):
            cell = table.cell(r+1, c)
            cell.text = v
            for p in cell.text_frame.paragraphs:
                p.font.size = Pt(12)
                p.font.color.rgb = DARK_GREY
                p.font.name = FONT_BODY
            tc = cell._tc; tcPr = tc.get_or_add_tcPr()
            sf = tcPr.makeelement(qn('a:solidFill'), {})
            fc = 'F5F5F5' if r % 2 == 0 else 'FFFFFF'
            sf.append(sf.makeelement(qn('a:srgbClr'), {'val': fc}))
            tcPr.append(sf)
    if n: slide_num(slide, n)

def code_slide(title, code_text, lang_label="Python", n=None):
    slide = prs.slides.add_slide(BLANK_LAYOUT)
    add_bg_shapes(slide, "content")
    _title_bar(slide, title)
    badge = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE,
        Inches(11.4), Inches(1.05), Inches(1.2), Inches(0.32)
    )
    badge.fill.solid()
    badge.fill.fore_color.rgb = TEAL
    badge.line.fill.background()
    badge_tf = badge.text_frame
    badge_tf.paragraphs[0].text = lang_label
    badge_tf.paragraphs[0].font.size = Pt(10)
    badge_tf.paragraphs[0].font.bold = True
    badge_tf.paragraphs[0].font.color.rgb = WHITE
    badge_tf.paragraphs[0].font.name = FONT_CODE
    badge_tf.paragraphs[0].alignment = PP_ALIGN.CENTER
    code_box = slide.shapes.add_shape(
        MSO_SHAPE.ROUNDED_RECTANGLE,
        Inches(0.6), Inches(1.4), Inches(12.1), Inches(5.6)
    )
    code_box.fill.solid()
    code_box.fill.fore_color.rgb = CODE_BG
    code_box.line.fill.background()
    tf = code_box.text_frame
    tf.word_wrap = True
    lines = code_text.strip().split('\n')
    for i, line in enumerate(lines):
        if i == 0:
            tf.paragraphs[0].text = line
            tf.paragraphs[0].font.size = Pt(9)
            tf.paragraphs[0].font.name = FONT_CODE
            tf.paragraphs[0].font.color.rgb = CODE_FG
            tf.paragraphs[0].space_after = Pt(1)
            tf.paragraphs[0].space_before = Pt(4)
        else:
            p = tf.add_paragraph()
            p.text = line
            p.font.size = Pt(9)
            p.font.name = FONT_CODE
            p.font.color.rgb = CODE_FG
            p.space_after = Pt(1)
    if n: slide_num(slide, n)


