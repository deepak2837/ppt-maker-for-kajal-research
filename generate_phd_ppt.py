    tf.paragraphs[0].text = title
    tf.paragraphs[0].font.size = Pt(size)
    tf.paragraphs[0].font.bold = True
    tf.paragraphs[0].font.color.rgb = NAVY
    tf.paragraphs[0].font.name = FONT_TITLE

